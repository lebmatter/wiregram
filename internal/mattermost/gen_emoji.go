//go:build ignore

// gen_emoji writes emoji_data.go from Mattermost's system emoji table, so
// reactions (which carry only a short name) can show the emoji itself.
//
// The source is server/public/model/emoji_data.go from the Mattermost repo
// (Apache-2.0). Fetch the tagged copy and regenerate:
//
//	curl -sfo /tmp/mm_emoji_data.txt https://raw.githubusercontent.com/mattermost/mattermost/server/public/v0.4.4/server/public/model/emoji_data.go
//	go run gen_emoji.go /tmp/mm_emoji_data.txt server/public/v0.4.4
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strconv"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: go run gen_emoji.go <emoji_data source> <upstream tag>")
		os.Exit(1)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(src, tag string) error {
	f, err := os.Open(src)
	if err != nil {
		return fmt.Errorf("open source: %w", err)
	}
	defer f.Close()

	entryRe := regexp.MustCompile(`^\s*"([^"]+)":\s*"([0-9a-f-]+)",\s*$`)
	var byName, byEmoji bytes.Buffer
	seen := make(map[string]bool)
	count := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := entryRe.FindStringSubmatch(sc.Text())
		if m == nil {
			// Skips the header and Mattermost's own logo, which is an image.
			continue
		}
		emoji, err := decode(m[2])
		if err != nil {
			return fmt.Errorf("entry %q: %w", m[1], err)
		}
		fmt.Fprintf(&byName, "\tcase %q:\n\t\treturn %q, true\n", m[1], emoji)
		// The first name in upstream order wins: "+1" before "thumbsup".
		key := stripVS(emoji)
		if !seen[key] {
			seen[key] = true
			fmt.Fprintf(&byEmoji, "\tcase %q:\n\t\treturn %q, true\n", key, m[1])
		}
		count++
	}
	if err := sc.Err(); err != nil {
		return fmt.Errorf("read source: %w", err)
	}
	if count == 0 {
		return fmt.Errorf("no emoji entries found in %s", src)
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by gen_emoji.go from Mattermost %s\n", tag)
	out.WriteString("// server/public/model/emoji_data.go. DO NOT EDIT.\n")
	out.WriteString("// Copyright (c) 2015-present Mattermost, Inc. Licensed under Apache-2.0.\n\n")
	out.WriteString("package mattermost\n\n")
	out.WriteString("// systemEmoji returns the emoji for a Mattermost system emoji name.\n")
	out.WriteString("func systemEmoji(name string) (string, bool) {\n\tswitch name {\n")
	out.Write(byName.Bytes())
	out.WriteString("\t}\n\treturn \"\", false\n}\n\n")
	out.WriteString("// systemEmojiName returns the Mattermost name for an emoji with its\n")
	out.WriteString("// variation selectors (U+FE0F) removed.\n")
	out.WriteString("func systemEmojiName(emoji string) (string, bool) {\n\tswitch emoji {\n")
	out.Write(byEmoji.Bytes())
	out.WriteString("\t}\n\treturn \"\", false\n}\n")

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("format output: %w", err)
	}
	if err := os.WriteFile("emoji_data.go", formatted, 0o644); err != nil {
		return fmt.Errorf("write emoji_data.go: %w", err)
	}
	return nil
}

// decode turns "263a-fe0f" into the string of those code points.
func decode(codes string) (string, error) {
	var b strings.Builder
	for _, hex := range strings.Split(codes, "-") {
		r, err := strconv.ParseUint(hex, 16, 32)
		if err != nil {
			return "", fmt.Errorf("code point %q: %w", hex, err)
		}
		b.WriteRune(rune(r))
	}
	return b.String(), nil
}

func stripVS(s string) string { return strings.ReplaceAll(s, "\ufe0f", "") }
